<?php

namespace App\Http\Controllers;

use App\Http\Controllers\Controller;
use App\Models\Stock;
use App\Models\StockRequest;
use App\Models\Department;
use Illuminate\Http\Request;
use Inertia\Inertia;
use Illuminate\Support\Facades\Auth;

class ReportController extends Controller
{
    public function index(Request $request)
    {
        $type = $request->get('type', 'system-overview');
        $startDate = $request->get('start_date');
        $endDate = $request->get('end_date');

        $user = Auth::user();
        
        // Handle role field string and relationships safely
        $roleName = is_string($user->role) ? $user->role : ($user->role->name ?? '');
        if (!$roleName && method_exists($user, 'roles') && $user->roles()->exists()) {
            $roleName = $user->roles->first()->name ?? '';
        }

        // Normalize role name for reliable checks
        $roleLower = strtolower((string) $roleName);
        $isAdmin = in_array($roleLower, ['admin', 'administrator']);
        $isInventoryManager = in_array($roleLower, ['inventory manager', 'inventory_manager']);
        $isHod = str_contains($roleLower, 'hod') || str_contains($roleLower, 'head');

        // All HODs are restricted to their own department's data. Admins see all requests by default.
        if ($isHod) {
            $departmentId = $user->department_id;
        } elseif ($isAdmin) {
            $departmentId = null; // admin should see all departments
        } else {
            $departmentId = $request->get('department_id');
        }

        // Stock availability and low stock reports can only be generated by Admin or Inventory Manager
        if (in_array($type, ['stock-availability', 'low-stock']) && $isHod) {
            abort(403, 'Unauthorized action.');
        }

        $departments = Department::all();

        if ($type === 'stock-availability') {
            $query = Stock::query();
            if ($startDate) $query->whereDate('created_at', '>=', $startDate);
            if ($endDate) $query->whereDate('created_at', '<=', $endDate);
            $data = $query->paginate(20)->withQueryString();
        } elseif ($type === 'low-stock') {
            $data = Stock::where('quantity', '<', 10)->paginate(20)->withQueryString();
        } elseif ($type === 'department') {
            $query = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                                ->with(['department', 'stock'])
                                ->selectRaw('employee_job.department_id, stock_requests.stock_id, count(stock_requests.id) as total_requests, sum(stock_requests.quantity) as total_items');
            if ($startDate) $query->whereDate('stock_requests.created_at', '>=', $startDate);
            if ($endDate) $query->whereDate('stock_requests.created_at', '<=', $endDate);
            if ($departmentId) $query->where('employee_job.department_id', $departmentId);
            $data = $query->groupBy('employee_job.department_id', 'stock_requests.stock_id')->get();
        } elseif ($type === 'request-status') {
            $query = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                                ->select('stock_requests.*')
                                ->with(['user', 'department', 'stock', 'processor'])
                                ->whereIn('stock_requests.status', ['approved', 'rejected']);
            if ($startDate) $query->whereDate('stock_requests.updated_at', '>=', $startDate);
            if ($endDate) $query->whereDate('stock_requests.updated_at', '<=', $endDate);
            if ($departmentId) $query->where('employee_job.department_id', $departmentId);
            $data = $query->latest('stock_requests.updated_at')->paginate(20)->withQueryString();
        } elseif ($type === 'summary') {
            $query = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                ->selectRaw('DATE(stock_requests.created_at) as date, count(stock_requests.id) as total_requests, sum(stock_requests.quantity) as total_quantity, sum(case when stock_requests.status = "approved" then stock_requests.quantity else 0 end) as approved_qty')
                ->groupBy('date')
                ->orderBy('date', 'desc');
            if ($startDate) $query->whereDate('stock_requests.created_at', '>=', $startDate);
            if ($endDate) $query->whereDate('stock_requests.created_at', '<=', $endDate);
            if ($departmentId) $query->where('employee_job.department_id', $departmentId);
            $data = $query->get();
        } elseif ($type === 'movements') {
            $query = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                ->select('stock_requests.*')
                ->with(['stock', 'department', 'user'])
                ->where('stock_requests.status', 'approved');
            if ($startDate) $query->whereDate('stock_requests.updated_at', '>=', $startDate);
            if ($endDate) $query->whereDate('stock_requests.updated_at', '<=', $endDate);
            if ($departmentId) $query->where('employee_job.department_id', $departmentId);
            $data = $query->latest('stock_requests.updated_at')->paginate(20)->withQueryString();
        } else {
            // system-overview
            if ($isHod) {
                $pendingRequests = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                    ->where('employee_job.department_id', $departmentId)
                    ->whereIn('stock_requests.status', ['pending_hod', 'pending_manager'])
                    ->count();
                $approvedRequests = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                    ->where('employee_job.department_id', $departmentId)
                    ->where('stock_requests.status', 'approved')
                    ->count();
                $rejectedRequests = StockRequest::join('employee_job', 'stock_requests.employee_id', '=', 'employee_job.employee_id')
                    ->where('employee_job.department_id', $departmentId)
                    ->where('stock_requests.status', 'rejected')
                    ->count();
            } else {
                $pendingRequests = StockRequest::whereIn('status', ['pending_hod', 'pending_manager'])->count();
                $approvedRequests = StockRequest::where('status', 'approved')->count();
                $rejectedRequests = StockRequest::where('status', 'rejected')->count();
            }

            $data = [
                'total_items' => Stock::count(),
                'total_quantity' => Stock::sum('quantity'),
                'pending_requests' => $pendingRequests,
                'approved_requests' => $approvedRequests,
                'rejected_requests' => $rejectedRequests,
            ];
        }

        if ($request->has('export') && $request->export == 'csv' && $type !== 'system-overview') {
            return $this->exportCsv($data, $type);
        }

        return Inertia::render('Inventory/ReportsIndex', [
            'data' => $data,
            'type' => $type,
            'departments' => $departments,
            'filters' => $request->only(['department_id', 'start_date', 'end_date']),
            'roleName' => $roleName,
        ]);
    }

    private function exportCsv($data, $type)
    {
        $filename = "report_{$type}_" . date('Y-m-d_H-i-s') . ".csv";
        $headers = [
            "Content-type"        => "text/csv",
            "Content-Disposition" => "attachment; filename=$filename",
            "Pragma"              => "no-cache",
            "Cache-Control"       => "must-revalidate, post-check=0, pre-check=0",
            "Expires"             => "0"
        ];

        $callback = function() use($data, $type) {
            $file = fopen('php://output', 'w');
            
            if ($type === 'stock-availability' || $type === 'low-stock') {
                fputcsv($file, ['ID', 'SKU', 'Item Name', 'Description', 'Quantity', 'Created At', 'Last Updated']);
                foreach ($data as $row) {
                    fputcsv($file, [$row->id, $row->sku, $row->name, $row->description, $row->quantity, $row->created_at, $row->updated_at]);
                }
            } elseif ($type === 'department') {
                fputcsv($file, ['Department', 'Item Name', 'Total Requests', 'Total Items Requested']);
                foreach ($data as $row) {
                    fputcsv($file, [$row->department->name ?? 'Unknown', $row->stock->name ?? 'Unknown', $row->total_requests, $row->total_items]);
                }
            } elseif ($type === 'request-status') {
                fputcsv($file, ['Request ID', 'Item', 'Requested By', 'Department', 'Quantity', 'Status', 'Processed By', 'Date']);
                foreach ($data as $row) {
                    fputcsv($file, [$row->id, $row->stock->name ?? '', $row->user->name ?? '', $row->department->name ?? '', $row->quantity, $row->status, $row->processor->name ?? 'N/A', $row->updated_at]);
                }
            } elseif ($type === 'summary') {
                fputcsv($file, ['Date', 'Total Requests', 'Total Qty Requested', 'Approved Qty']);
                foreach ($data as $row) {
                    fputcsv($file, [$row->date, $row->total_requests, $row->total_quantity, $row->approved_qty]);
                }
            } elseif ($type === 'movements') {
                fputcsv($file, ['Date', 'Item', 'Department', 'Requester', 'Qty Moved Out']);
                foreach ($data as $row) {
                    fputcsv($file, [$row->updated_at, $row->stock->name ?? '', $row->department->name ?? '', $row->user->name ?? '', $row->quantity]);
                }
            }
            
            fclose($file);
        };

        return response()->stream($callback, 200, $headers);
    }
}
